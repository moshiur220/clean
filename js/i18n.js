  /**
   * Get a translation string by dot-notation key.
   * Falls back to English if key not found in current language.
   * @param {string} key — e.g. 'nav.dashboard', 'auth.signIn'
   * @param {Object} [vars] — optional substitutions { name: 'David' }
   */
  t(key, vars = {}) {
    const keys = key.split('.');
    let val = this.translations[this.currentLang];
    for (const k of keys) {
      if (val && typeof val === 'object' && k in val) {
        val = val[k];
      } else {
        // Fallback to English
        val = this.translations['en'];
        for (const fk of keys) {
          if (val && typeof val === 'object' && fk in val) {
            val = val[fk];
          } else {
            return key; // ultimate fallback
          }
        }
        break;
      }
    }
    if (typeof val !== 'string') return key;
    // Substitute variables
    return val.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  },

  /**
   * Set the current language and persist it.
   * Triggers a full page re-render.
   * @param {'en'|'sv'} lang
   */
  setLanguage(lang) {
    if (!this.translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('ci_lang', lang);
    // Update <html lang> attribute
    document.documentElement.lang = lang;
    // Update static DOM elements with data-i18n
    this.applyStaticTranslations();
    // Re-render current route
    if (typeof Router !== 'undefined' && Router.render) {
      Router.render();
    }
    // Show confirmation toast
    const msg = lang === 'sv' ? 'Språk ändrat till Svenska 🇸🇪' : 'Language changed to English 🇬🇧';
    if (typeof Utils !== 'undefined') Utils.showToast(msg, 'success', 2500);
  },

  /**
   * Apply translations to all static HTML elements with [data-i18n] attributes.
   * Also updates language toggle button text.
   */
  applyStaticTranslations() {
    const lang = this.currentLang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });
    // Update language toggle buttons
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.textContent = this.t('lang.switchTo');
      btn.title = this.t('lang.label') + ': ' + this.t('lang.current');
    });
    document.querySelectorAll('.lang-flag').forEach(flag => {
      flag.textContent = lang === 'sv' ? '🇸🇪' : '🇬🇧';
    });
  },

  /**
   * Toggle between English and Swedish
   */
  toggle() {
    this.setLanguage(this.currentLang === 'sv' ? 'en' : 'sv');
  },

  /**
   * Initialize i18n — call once on app load
   */
  init() {
    document.documentElement.lang = this.currentLang;
    this.applyStaticTranslations();
  },

  /**
   * Return date string in the current locale
   * @param {string|Date} dateStr
   * @param {'short'|'long'|'date-only'} format
   */
  formatDate(dateStr, format = 'short') {
    if (!dateStr) return '';
    const date = new Date(dateStr);
    if (isNaN(date)) return dateStr;
    const locale = this.currentLang === 'sv' ? 'sv-SE' : 'en-US';
    if (format === 'date-only') {
      return date.toLocaleDateString(locale, { day: 'numeric', month: 'short', year: 'numeric' });
    }
    if (format === 'long') {
      return date.toLocaleDateString(locale, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' });
    }
    return date.toLocaleDateString(locale, { day: 'numeric', month: 'short', year: 'numeric' });
  },

  /**
   * Return today's date string in current locale
   */
  formatToday() {
    return this.formatDate(new Date(), 'long');
  },
